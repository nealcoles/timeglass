// Generates src/api/schema.d.ts from the API's committed OpenAPI document (#31).
//
//   node scripts/generate-api-types.mjs          writes the file
//   node scripts/generate-api-types.mjs --check  fails if the file is out of date
//
// The output goes through Prettier with the project's settings, so the committed file passes
// `npm run format:check` and the check doesn't depend on who ran the generator.
import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import openapiTS, { astToString } from 'openapi-typescript';
import * as prettier from 'prettier';

const specUrl = new URL('../../src/Timeglass.Api/openapi.json', import.meta.url);
const outputUrl = new URL('../src/api/schema.d.ts', import.meta.url);
const outputPath = fileURLToPath(outputUrl);
const check = process.argv.includes('--check');

const ast = await openapiTS(specUrl);
const header =
    '// Generated by scripts/generate-api-types.mjs from src/Timeglass.Api/openapi.json.\n' +
    '// Do not edit by hand: run `npm run generate:api`.\n\n';
const generated = await prettier.format(header + astToString(ast), {
    ...(await prettier.resolveConfig(outputPath)),
    filepath: outputPath,
});

if (!check) {
    await writeFile(outputUrl, generated);
    console.log(`Wrote ${outputPath}`);
    process.exit(0);
}

const normalize = (text) => text.replace(/\r\n/g, '\n');
const current = await readFile(outputUrl, 'utf8').catch(() => null);
if (current === null || normalize(current) !== normalize(generated)) {
    console.error(
        'src/api/schema.d.ts is out of date with src/Timeglass.Api/openapi.json.\n' +
            'Run `npm run generate:api` in web/ and commit the result.',
    );
    process.exit(1);
}
console.log('src/api/schema.d.ts is up to date.');
